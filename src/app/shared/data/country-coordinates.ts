/** Returns [left %, top %] for the equirectangular map image. */
export function countryMarker(name: string): { left: number; top: number } | null {
  if (!name) return null;
  const key = name.trim().toLowerCase().replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ');
  const point =
    COORDINATES[key] ??
    COORDINATES[key.replace(/ the$/, '')] ??
    Object.entries(COORDINATES).find(([candidate]) =>
      key.includes(candidate) || candidate.includes(key),
    )?.[1];
  if (!point) return null;
  const [lat, lng] = point;
  return {
    left: ((lng + 180) / 360) * 100,
    top: ((90 - lat) / 180) * 100,
  };
}
